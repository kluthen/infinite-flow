/**
 * v2.0 chunk 16, the rolling display at every barline: in each layout a session runs eight
 * phrases on the fake audio clock, and at every barline each system position shows what the
 * rolling plan gives (one system: whole phrases alternate, odd on top; split: bars 1-2 on top and
 * 3-4 below, the next phrase's opening on top from bar 3), the playhead band sits in the measure
 * being played and only there, and at least one measure is on screen ahead of it, a late
 * look-ahead phrase included. A note once drawn never changes until its system is refilled, and a
 * system the playhead leaves fades out at once before what comes next enters. Runs against the
 * workspace harness (port 4175), its look-ahead phrases generated by the real worker.
 */
import { expect, test, type Page } from '@playwright/test'

import { holdGeneration, releaseGeneration, generationsSettled } from '../release/harness-helpers'
import {
  DESKTOP,
  gotoSessionHarness,
  PHONE,
  PREGENERATION_OFF,
  readyToStart,
  sessionState,
  startSession,
  toCountInMiddle,
} from './session-helpers'
import {
  drawnKeys,
  expectedSystems,
  markSystems,
  playheadPosition,
  readAhead,
  readStaff,
  rollingLog,
  sessionNotationErrors,
  settledStaff,
  startRollingLog,
  toBarline,
  untilReady,
  type Layout,
  type StaffReading,
} from './rolling-helpers'

/** The two layouts, each at a window that selects it at the start. */
const LAYOUTS = [
  { layout: 'one-system', size: DESKTOP },
  { layout: 'split', size: PHONE },
] as const satisfies readonly { layout: Layout; size: typeof DESKTOP | typeof PHONE }[]

/**
 * Intent: land at `size`, with the page URL's `search` if any, make a phrase ready and start a
 * session in `layout`.
 */
async function startIn(
  page: Page,
  size: typeof DESKTOP | typeof PHONE,
  layout: Layout,
  search = '',
) {
  await gotoSessionHarness(page, size, search)
  await readyToStart(page)
  await startRollingLog(page)
  await startSession(page)
  expect((await sessionState(page)).heldLayout).toBe(layout)
}

/**
 * Intent: assert one barline's reading: the playhead on the measure, both positions as the plan
 * gives them for what is readied, the one band in the playhead's measure of its own system, and
 * at least one measure on screen ahead of it.
 */
function expectBarline(
  reading: StaffReading,
  layout: Layout,
  phraseNumber: number,
  measureIndex: number,
): void {
  const where = `phrase ${phraseNumber}, measure ${measureIndex + 1}`
  const { state } = reading
  expect(state.phase, where).toBe('running')
  expect(state.playhead, where).toEqual({ phraseNumber, measureIndex })
  const latestReady = state.latestReady ?? 0
  expect([phraseNumber, phraseNumber + 1], where).toContain(latestReady)
  const expected = expectedSystems(layout, phraseNumber, measureIndex, latestReady)
  expect(state.systems, where).toEqual(expected)
  expect(drawnKeys(reading), where).toEqual(expected)
  expect(reading.settledPerPosition, where).toBeLessThanOrEqual(1)
  expect(reading.bands, where).toBe(1)
  const here = playheadPosition(layout, phraseNumber, measureIndex)
  expect(reading[here]?.bandMeasure, where).toBe(measureIndex)
  expect(reading[here === 'top' ? 'bottom' : 'top']?.bandMeasure ?? null, where).toBeNull()
  expect(readAhead(reading, phraseNumber, measureIndex), where).toBeGreaterThanOrEqual(1)
}

/**
 * Intent: from a session in its count-in with phrase 2 readied, move barline by barline through
 * phrases 1 to `phrases`, waiting at each phrase's first barline for the next phrase to be readied
 * (it is requested as that phrase starts sounding), and hand each settled reading to `check`
 * along with the reading of the barline before.
 */
async function walkBarlines(
  page: Page,
  phrases: number,
  check: (reading: StaffReading, phrase: number, measure: number, before: StaffReading) => void,
): Promise<void> {
  await settledStaff(page)
  for (let phrase = 1; phrase <= phrases; phrase += 1) {
    for (let measure = 0; measure < 4; measure += 1) {
      await markSystems(page, `${phrase}.${measure}`)
      const before = await readStaff(page)
      await toBarline(page, phrase, measure)
      if (measure === 0 && phrase >= 2) {
        // Before the next phrase is readied: the playhead's system alone, three measures ahead.
        check(await settledStaff(page), phrase, measure, before)
        await untilReady(page, phrase + 1)
      }
      check(await settledStaff(page), phrase, measure, before)
    }
  }
}

for (const { layout, size } of LAYOUTS) {
  // @test-link [[module_session_rolling_display]]
  // @test-link [[req_rolling_practice_session]]
  // @test-link [[rule_playhead_follows_audio_clock]]
  // @test-link [[rule_look_ahead_deadline]]
  // @test-link [[rule_phrase_one_is_idle_phrase]]
  test(`${layout}: eight phrases, each system checked at every barline`, async ({ page }) => {
    test.setTimeout(300_000)
    await startIn(page, size, layout)

    // The count-in: phrase 1 as Idle drew it, no band; phrase 2 enters below on one system, and
    // waits whole in the split layout, whose two positions phrase 1 fills.
    await toCountInMiddle(page)
    await untilReady(page, 2)
    const countIn = await settledStaff(page)
    expect(countIn.state.playhead).toBeNull()
    expect(countIn.bands).toBe(0)
    if (layout === 'one-system') {
      expect(drawnKeys(countIn)).toEqual({ top: '1:whole', bottom: '2:whole' })
      expect(countIn.state.waiting).toEqual([])
      const entered = (await rollingLog(page)).filter((entry) => entry.kind === 'enter')
      expect(entered).toEqual([expect.objectContaining({ position: 'bottom', key: '2:whole' })])
    } else {
      expect(drawnKeys(countIn)).toEqual({ top: '1:opening', bottom: '1:closing' })
      expect(countIn.state.waiting).toEqual(['2:opening', '2:closing'])
    }

    await walkBarlines(page, 8, (reading, phrase, measure) => {
      expectBarline(reading, layout, phrase, measure)
      if (measure > 0 || phrase === 1) {
        expect(reading.state.latestReady, `phrase ${phrase}`).toBe(phrase + 1)
      }
    })
    expect(await sessionNotationErrors(page)).toEqual([])
  })

  // @test-link [[module_session_staff_refill]]
  test(`${layout}: a drawn note never changes until its system is refilled`, async ({ page }) => {
    test.setTimeout(180_000)
    await startIn(page, size, layout)
    await toCountInMiddle(page)
    await untilReady(page, 2)

    let kept = 0
    let refilled = 0
    await walkBarlines(page, 3, (reading, phrase, measure, before) => {
      for (const position of ['top', 'bottom'] as const) {
        const now = reading[position]
        const was = before[position]
        const where = `${position}, phrase ${phrase}, measure ${measure + 1}`
        if (now === null || was === null || now.key !== was.key) {
          // Refilled (or blank): a new unit, never the one marked before the barline.
          if (now !== null) expect(now.unitMark, where).toBeNull()
          refilled += 1
          continue
        }
        // The same slot: the very same unit and SVG nodes, and the same notes drawn the same way.
        expect(now.unitMark, where).toBe(was.unitMark)
        expect(now.svgMark, where).toBe(was.svgMark)
        expect(now.svgMark, where).not.toBeNull()
        expect(now.noteIds, where).toEqual(was.noteIds)
        expect(now.notes, where).toEqual(was.notes)
        kept += 1
      }
    })
    expect(kept).toBeGreaterThan(0)
    expect(refilled).toBeGreaterThan(0)
  })
}

// @test-link [[module_session_rolling_display]]
// @test-link [[rule_look_ahead_deadline]]
test('split: a look-ahead phrase late past its deadline leaves a measure of read-ahead', async ({
  page,
}) => {
  test.setTimeout(180_000)
  await startIn(page, PHONE, 'split', PREGENERATION_OFF)
  await toCountInMiddle(page)
  await untilReady(page, 2)
  for (let measure = 0; measure < 4; measure += 1) await toBarline(page, 1, measure)

  // Phrase 3 is requested as phrase 2 starts sounding; it is held until past its deadline, the
  // start of phrase 2's last measure.
  await holdGeneration(page)
  const settledBefore = await generationsSettled(page)
  await toBarline(page, 2, 0)
  expectBarline(await settledStaff(page), 'split', 2, 0)
  await toBarline(page, 2, 1)
  expectBarline(await settledStaff(page), 'split', 2, 1)

  // From bar 3 the top waits for phrase 3: bar 4, below, is the one measure ahead.
  await toBarline(page, 2, 2)
  const waitingForThree = await settledStaff(page)
  expectBarline(waitingForThree, 'split', 2, 2)
  expect(drawnKeys(waitingForThree)).toEqual({ top: null, bottom: '2:closing' })
  expect(readAhead(waitingForThree, 2, 2)).toBe(1)

  // At the deadline phrase 2 is repeated as phrase 3: its opening is on top as bar 4 starts.
  await toBarline(page, 2, 3)
  expect((await readStaff(page)).state.systems).toEqual({ top: '3:opening', bottom: '2:closing' })
  const atDeadline = await settledStaff(page)
  expectBarline(atDeadline, 'split', 2, 3)
  expect(readAhead(atDeadline, 2, 3)).toBe(2)
  expect(atDeadline.state.latestReady).toBe(3)

  // Both held attempts, released late, are dropped as cancelled: the carry-in attempt, cut over
  // at the standalone reserve before the deadline, and the standalone attempt requested then,
  // cancelled at the deadline. Phrase 3 stays the repeat.
  const carryIns = await page.evaluate(() =>
    window.__workspaceHarness.generationRequests().map((request) => request.carryIn),
  )
  expect(carryIns.slice(-2)).toEqual([true, false])
  await releaseGeneration(page)
  await expect.poll(() => generationsSettled(page), { timeout: 30_000 }).toBe(settledBefore + 2)
  expect((await sessionState(page)).latestReady).toBe(3)

  // Phrase 3 plays as usual, and phrase 4 is looked ahead again.
  await toBarline(page, 3, 0)
  await untilReady(page, 4)
  for (let measure = 0; measure < 4; measure += 1) {
    await toBarline(page, 3, measure)
    expectBarline(await settledStaff(page), 'split', 3, measure)
  }
})

/** Where each layout's playhead first leaves a system, and what follows there. */
const REFILLS = [
  // One system: phrase 2's first barline leaves phrase 1 on top; phrase 3 comes once readied.
  {
    layout: 'one-system',
    size: DESKTOP,
    at: [2, 0],
    left: '1:whole',
    band: '2:whole',
    next: '3:whole',
  },
  // Split: phrase 1's third barline leaves its opening on top; phrase 2's opening comes there.
  {
    layout: 'split',
    size: PHONE,
    at: [1, 2],
    left: '1:opening',
    band: '1:closing',
    next: '2:opening',
  },
] as const

for (const { layout, size, at, left, band, next } of REFILLS) {
  // @test-link [[module_session_staff_refill]]
  test(`${layout}: the system the playhead leaves fades out at once, then refills`, async ({
    page,
  }) => {
    test.setTimeout(120_000)
    await startIn(page, size, layout)
    await toCountInMiddle(page)
    await untilReady(page, 2)
    const [phrase, measure] = at
    for (let p = 1; p <= phrase; p += 1) {
      for (let m = 0; m < 4 && (p < phrase || m < measure); m += 1) await toBarline(page, p, m)
    }
    const logBefore = (await rollingLog(page)).length

    await toBarline(page, phrase, measure)
    const log = (await rollingLog(page)).slice(logBefore)
    // The unit left starts fading in the very update that moves the band into the other system.
    const fade = log.find((entry) => entry.kind === 'fade-out')
    expect(fade).toEqual(expect.objectContaining({ position: 'top', key: left }))
    expect(log).toContainEqual(
      expect.objectContaining({ kind: 'band', position: 'bottom', key: band, batch: fade?.batch }),
    )

    // Then what comes next enters the emptied position as a new unit, with its entrance fade.
    await untilReady(page, Number(next.split(':')[0]))
    const settled = await settledStaff(page)
    expect(drawnKeys(settled).top).toBe(next)
    const after = (await rollingLog(page)).slice(logBefore)
    const fadeAt = after.findIndex((entry) => entry.kind === 'fade-out')
    const enterAt = after.findIndex((entry) => entry.kind === 'enter' && entry.key === next)
    expect(enterAt).toBeGreaterThan(fadeAt)
    expect(after.filter((entry) => entry.kind === 'fade-out')).toHaveLength(1)
    const animation = await page
      .locator('.staff-frame [data-system-position="top"] > .staff-content')
      .evaluate((unit) => getComputedStyle(unit).animationName)
    expect(animation).toBe('staff-fade-in')
  })
}
